package skills.examples.data.serviceRequestModel;

import java.util.List;

public class SkillTagRequest {
    private String tagId;
    private String origTagId;
    private String tagValue;

    List<String> skillIds;

    public List<String> getSkillIds() {
        return skillIds;
    }

    public void setSkillIds(List<String> skillIds) {
        this.skillIds = skillIds;
    }

    public SkillTagRequest(String tagId, String tagValue) {
        this.tagValue = tagValue;
        this.tagId = tagId;
    }

    public String getTagId() {
        return tagId;
    }

    public void setTagId(String tagId) {
        this.tagId = tagId;
    }
    
    public String getOrigTagId() {
        return origTagId;
    }

    public void setOrigTagId(String origTagId) {
        this.origTagId = origTagId;
    }

    public String getTagValue() {
        return tagValue;
    }

    public void setTagValue(String tagValue) {
        this.tagValue = tagValue;
    }
}
